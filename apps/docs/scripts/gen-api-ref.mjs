#!/usr/bin/env node
/**
 * 从 packages/sdk/spec/openapi.platform.json 生成 docs/reference/api.md。
 *
 * 不引入 vitepress-openapi 之类的 plugin —— 一个手写的 markdown emitter 就够，
 * 输出可预测、build 不依赖运行时网络、PR 里 diff 看 spec 漂移直接可读。
 *
 * 触发：apps/docs/package.json 的 prebuild hook。
 *
 * 维护契约：
 *  - server 改 platform-spec.ts → pnpm --filter @kintsugi/sdk gen 刷快照
 *  - docs build 自动从快照生成 → 不存在文档过时
 *  - 想手写补充 → 编辑 reference/instant-api.md（概念向）；本文件只重生成 api.md
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..', '..', '..');
const SPEC_PATH = path.join(REPO_ROOT, 'packages', 'sdk', 'spec', 'openapi.platform.json');
const OUT_PATH = path.join(__dirname, '..', 'docs', 'reference', 'api.md');

const METHOD_ORDER = ['get', 'post', 'put', 'patch', 'delete', 'head', 'options'];

function escMd(s) {
  return String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function refLabel(ref) {
  return ref.replace('#/components/schemas/', '');
}

/** 浅层 schema 描述，专为表格渲染。深层结构提供 schema 引用名让读者跳到下方定义。 */
function describeSchema(schema, schemas) {
  if (!schema) return '—';
  if (schema.$ref) {
    const name = refLabel(schema.$ref);
    return `[\`${name}\`](#${name.toLowerCase()})`;
  }
  if (schema.type === 'array') {
    return `array of ${describeSchema(schema.items, schemas)}`;
  }
  if (schema.enum) {
    return `enum: ${schema.enum.map((v) => `\`${v}\``).join(' \\| ')}`;
  }
  if (schema.type) {
    return schema.format ? `${schema.type} (${schema.format})` : schema.type;
  }
  if (schema.properties) return 'object';
  return '—';
}

function renderEndpoint(method, route, op, schemas) {
  const lines = [];
  lines.push(`### \`${method.toUpperCase()} ${route}\``);
  lines.push('');
  if (op.summary) lines.push(`**${escMd(op.summary)}**`);
  if (op.description) lines.push('', op.description);
  if (op.operationId) lines.push('', `\`operationId\`: \`${op.operationId}\``);

  // Parameters
  if (op.parameters?.length) {
    lines.push('', '**Parameters**');
    lines.push('');
    lines.push('| name | in | type | required |');
    lines.push('|---|---|---|---|');
    for (const p of op.parameters) {
      lines.push(`| ${p.name} | ${p.in} | ${describeSchema(p.schema, schemas)} | ${p.required ? '✓' : ''} |`);
    }
  }

  // Request body
  const reqJson = op.requestBody?.content?.['application/json']?.schema;
  if (reqJson) {
    lines.push('', '**Request body**');
    lines.push('');
    lines.push(`- Content-Type: \`application/json\``);
    lines.push(`- Schema: ${describeSchema(reqJson, schemas)}`);
  }

  // Responses
  if (op.responses) {
    lines.push('', '**Responses**');
    lines.push('');
    lines.push('| status | schema |');
    lines.push('|---|---|');
    for (const status of Object.keys(op.responses).sort()) {
      const r = op.responses[status];
      const schema = r.content?.['application/json']?.schema;
      lines.push(`| ${status} | ${schema ? describeSchema(schema, schemas) : '—'} |`);
    }
  }

  if (op.security) {
    const names = op.security
      .flatMap((s) => Object.keys(s))
      .filter((v, i, a) => a.indexOf(v) === i);
    if (names.length === 0) {
      lines.push('', '**Auth**: 公开（无认证要求）');
    } else {
      lines.push('', `**Auth**: ${names.map((n) => `\`${n}\``).join(' / ')}`);
    }
  }

  lines.push('');
  return lines.join('\n');
}

function renderSchemaTable(name, def) {
  const lines = [];
  lines.push(`#### ${name}`);
  lines.push('');
  if (def.description) lines.push(escMd(def.description), '');
  if (def.type === 'object' && def.properties) {
    lines.push('| field | type | required | nullable | desc |');
    lines.push('|---|---|---|---|---|');
    const required = new Set(def.required ?? []);
    for (const [field, fdef] of Object.entries(def.properties)) {
      const t = fdef.$ref ? `[${refLabel(fdef.$ref)}](#${refLabel(fdef.$ref).toLowerCase()})` : describeSchema(fdef);
      lines.push(`| \`${field}\` | ${t} | ${required.has(field) ? '✓' : ''} | ${fdef.nullable ? '✓' : ''} | ${escMd(fdef.description ?? '')} |`);
    }
  } else {
    lines.push('```json');
    lines.push(JSON.stringify(def, null, 2));
    lines.push('```');
  }
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const raw = await readFile(SPEC_PATH, 'utf8');
  const spec = JSON.parse(raw);
  const schemas = spec.components?.schemas ?? {};

  const out = [];
  out.push('---');
  out.push('outline: deep');
  out.push('---');
  out.push('');
  out.push('# 平台 API 参考');
  out.push('');
  out.push(`<!-- AUTO-GENERATED by apps/docs/scripts/gen-api-ref.mjs from packages/sdk/spec/openapi.platform.json. DO NOT EDIT. -->`);
  out.push('');
  out.push(`> **${spec.info?.title ?? 'Kintsugi'}** v${spec.info?.version ?? ''}`);
  out.push('>');
  out.push(`> ${spec.info?.description ?? ''}`);
  out.push('');
  out.push('::: tip 这是平台稳定 API 的自动生成参考');
  out.push('内容来自 server 的 OpenAPI spec，每次 docs build 重生成；改 server controller → 跑 `pnpm --filter @kintsugi/sdk gen` 刷快照 → docs 自动跟。');
  out.push('每个 application 还有自己的 Instant API（dataset 字段级 schema），见 [Instant API 概念](./instant-api)。');
  out.push(':::');
  out.push('');

  // Endpoints
  out.push('## Endpoints');
  out.push('');
  const paths = spec.paths ?? {};
  for (const route of Object.keys(paths).sort()) {
    const item = paths[route];
    for (const method of METHOD_ORDER) {
      const op = item[method];
      if (!op) continue;
      out.push(renderEndpoint(method, route, op, schemas));
    }
  }

  // Schemas
  out.push('## Schemas');
  out.push('');
  for (const name of Object.keys(schemas).sort()) {
    out.push(renderSchemaTable(name, schemas[name]));
  }

  await mkdir(path.dirname(OUT_PATH), { recursive: true });
  await writeFile(OUT_PATH, out.join('\n'));
  const endpointCount = Object.values(paths).reduce(
    (n, item) => n + METHOD_ORDER.filter((m) => item[m]).length,
    0,
  );
  console.log(
    `[gen-api-ref] wrote ${path.relative(REPO_ROOT, OUT_PATH)} — ${endpointCount} endpoints, ${Object.keys(schemas).length} schemas`,
  );
}

await main();
